<?php declare(strict_types=1);

namespace Application\Console;

use FilesystemIterator;
use RecursiveDirectoryIterator;
use RecursiveIteratorIterator;
use RuntimeException;
use SplFileInfo;
use Symfony\Component\Console\Attribute\AsCommand;
use Symfony\Component\Console\Command\Command;
use Symfony\Component\Console\Input\InputInterface;
use Symfony\Component\Console\Output\OutputInterface;
use Symfony\Component\Console\Style\SymfonyStyle;

/**
 * CacheClearCommand
 *
 * Removes the content of the cache directory (`storage/cache` by default), except its `.gitignore` file, so that the
 * caches are regenerated by the next request, or by the `cache:warmup` command.
 */
#[AsCommand(name: 'cache:clear', description: 'Removes the content of the cache directory')]
class CacheClearCommand extends Command
{

    public function __construct(
        private readonly ?string $directory = null
    ) {
        parent::__construct();
    }

    protected function execute(InputInterface $input, OutputInterface $output): int
    {
        $directory = rtrim($this->directory ?? cache_path(), '\\/');
        $io = new SymfonyStyle($input, $output);

        if (!is_dir($directory)) {
            $io->success(sprintf('The cache directory "%s" does not exist, nothing to clear.', $directory));

            return Command::SUCCESS;
        }

        $iterator = new RecursiveIteratorIterator(
            new RecursiveDirectoryIterator($directory, FilesystemIterator::SKIP_DOTS),
            RecursiveIteratorIterator::CHILD_FIRST
        );

        $removed = 0;

        /** @var SplFileInfo $file */
        foreach ($iterator as $file) {
            if ($file->getPath() === $directory && $file->getFilename() === '.gitignore') {
                continue;
            }

            // The directories are removed once empty, their content coming first (CHILD_FIRST)
            $isDirectory = $file->isDir() && !$file->isLink();
            if (!($isDirectory ? @rmdir($file->getPathname()) : @unlink($file->getPathname()))) {
                throw new RuntimeException(sprintf('Unable to remove "%s".', $file->getPathname()));
            }

            $removed += $isDirectory ? 0 : 1;
        }

        $io->success(sprintf('The cache directory "%s" has been cleared (%d file(s) removed).', $directory, $removed));

        return Command::SUCCESS;
    }
}
